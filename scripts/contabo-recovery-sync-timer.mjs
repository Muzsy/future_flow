// Linux counterpart of contabo-recovery-sync-task.ps1: an hourly systemd *user*
// timer for the pinned local encrypted-copy sync. It stores no password or key,
// copies no credential and runs with the signed-in operator's own rights only.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import { dirname, isAbsolute, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import {
  assertLinuxPrivatePath,
  operatorSecretsDirectory,
} from './lib/operator-platform.mjs';

export const SERVICE = 'alterward-recovery-sync.service';
export const TIMER = 'alterward-recovery-sync.timer';
export const sourcePaths = [
  'scripts/recovery-local.mjs',
  'scripts/supabase-managed-retention.mts',
  'scripts/legacy-recovery-retention.mts',
  'scripts/lib/managed-retention.ts',
  'scripts/lib/local-managed-recovery.ts',
  'scripts/lib/private-report.ts',
  'scripts/lib/operator-platform.mjs',
  'scripts/ops/contabo-managed-expiry.py',
  'scripts/ops/local-managed-recovery.py',
  'scripts/ops/legacy-recovery-retention.py',
  'scripts/ops/contabo-recovery-install.py',
  'scripts/contabo-daily.mjs',
  'scripts/ops/contabo-daily-install.py',
  'scripts/ops/contabo-backup.py',
  'scripts/contabo-recovery-sync-timer.mjs',
  'pnpm-lock.yaml',
  'package.json',
];

// Unit files cannot quote arbitrary text safely; accept only plain absolute paths.
const SAFE_PATH = /^\/[A-Za-z0-9._@+/-]+$/;
export function assertSafeUnitPath(path) {
  if (!isAbsolute(path) || !SAFE_PATH.test(path) || path.includes('..'))
    throw Error('Plain absolute path required for the systemd unit');
  return path;
}

export function renderUnits({ node, wrapper, workspace }) {
  for (const path of [node, wrapper, workspace]) assertSafeUnitPath(path);
  return {
    [SERVICE]: [
      '[Unit]',
      'Description=Alterward pinned local managed recovery sync',
      '',
      '[Service]',
      'Type=oneshot',
      `WorkingDirectory=${workspace}`,
      `ExecStart=${node} ${wrapper}`,
      'TimeoutStartSec=900',
      'NoNewPrivileges=yes',
      '',
    ].join('\n'),
    [TIMER]: [
      '[Unit]',
      'Description=Hourly Alterward pinned local managed recovery sync',
      '',
      '[Timer]',
      // :11 UTC leaves time before the next server lifecycle tick, as on Windows.
      'OnCalendar=*-*-* *:11:00 UTC',
      'Persistent=true',
      `Unit=${SERVICE}`,
      '',
      '[Install]',
      'WantedBy=timers.target',
      '',
    ].join('\n'),
  };
}

export function renderWrapper({ node, python, secrets, workspace, log, pins }) {
  const config = { node, python, secrets, workspace, log, pins };
  return `// Generated by contabo-recovery-sync-timer.mjs. Do not edit; reinstall from reviewed source.
import { createHash } from 'node:crypto';
import { closeSync, openSync, readFileSync, writeSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
const config = JSON.parse(${JSON.stringify(JSON.stringify(config))});
const fd = openSync(config.log, 'w', 0o600);
try {
  for (const pin of config.pins) {
    const hash = createHash('sha256').update(readFileSync(pin.path)).digest('hex');
    if (hash !== pin.hash) throw Error('Reviewed source or runtime changed');
  }
  if (process.execPath !== config.node) throw Error('Original Node required');
  const result = spawnSync(
    config.node,
    ['--env-file=.env', 'scripts/recovery-local.mjs', '--sync-and-expire'],
    {
      cwd: config.workspace,
      env: {
        ...process.env,
        ALTERWARD_PYTHON: config.python,
        ALTERWARD_SSH_SECRETS_DIR: config.secrets,
      },
      stdio: ['ignore', fd, fd],
    },
  );
  process.exitCode = result.status ?? 1;
} catch {
  process.exitCode = 1;
  writeSync(fd, 'Managed recovery sync failed; inspect private evidence. The server receipt becomes stale if this persists.\\n');
} finally {
  closeSync(fd);
}
`;
}

function sha256(path) {
  return createHash('sha256').update(fs.readFileSync(path)).digest('hex');
}
function regularFile(path) {
  const info = fs.lstatSync(path);
  if (!info.isFile() || info.isSymbolicLink() || info.nlink !== 1)
    throw Error('Original regular file required');
  return path;
}
function tsxFiles(directory) {
  const out = [];
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isSymbolicLink()) throw Error('Original tsx files required');
    if (entry.isDirectory()) out.push(...tsxFiles(path));
    else if (entry.isFile()) out.push(path);
  }
  return out.sort();
}

export function collectPins({ workspace, node, python }) {
  const commit = execFileSync('git', ['rev-parse', 'HEAD'], {
    cwd: workspace,
    encoding: 'utf8',
  }).trim();
  const pins = [];
  for (const path of sourcePaths) {
    const absolute = regularFile(join(workspace, path));
    const bytes = fs.readFileSync(absolute);
    if (
      !bytes.equals(
        execFileSync('git', ['show', `${commit}:${path}`], { cwd: workspace }),
      )
    )
      throw Error('Exact committed source required');
    pins.push({ path: absolute, hash: sha256(absolute) });
  }
  for (const runtime of [node, python])
    pins.push({ path: regularFile(runtime), hash: sha256(runtime) });
  for (const file of tsxFiles(join(workspace, 'node_modules/tsx/dist')))
    pins.push({ path: file, hash: sha256(file) });
  return pins;
}

function systemctl(...args) {
  return execFileSync('systemctl', ['--user', ...args], {
    encoding: 'utf8',
    timeout: 30000,
  });
}

// Every action works on the checkout that contains this reviewed script, never
// on whatever directory it happens to be started from.
function scriptWorkspace() {
  const workspace = fs.realpathSync(
    join(dirname(fileURLToPath(import.meta.url)), '..'),
  );
  if (fs.realpathSync(process.cwd()) !== workspace)
    throw Error('Run from the reviewed checkout root');
  return workspace;
}

function install() {
  const workspace = scriptWorkspace();
  const node = fs.realpathSync(process.execPath);
  const python = process.env.ALTERWARD_PYTHON ?? '';
  const secrets = operatorSecretsDirectory();
  if (!isAbsolute(python) || fs.realpathSync(python) !== python)
    throw Error('Explicit real absolute operator Python required');
  if (node !== process.execPath)
    throw Error('Run with the real Node binary, not a symlink');
  assertLinuxPrivatePath(join(workspace, '.local'), true);
  const privateDir = join(workspace, '.local/contabo-recovery');
  fs.mkdirSync(privateDir, { recursive: true, mode: 0o700 });
  assertLinuxPrivatePath(privateDir, true);
  const wrapper = join(privateDir, 'managed-sync-timer.mjs');
  const log = join(privateDir, 'managed-sync-timer.log');
  const unitDirectory = join(os.homedir(), '.config/systemd/user');
  const units = renderUnits({ node, wrapper, workspace });
  if (
    fs.existsSync(wrapper) ||
    Object.keys(units).some((name) => fs.existsSync(join(unitDirectory, name)))
  )
    throw Error('Existing timer requires reviewed source update');
  const pins = collectPins({ workspace, node, python });
  fs.mkdirSync(unitDirectory, { recursive: true, mode: 0o700 });
  const written = [];
  try {
    fs.writeFileSync(
      wrapper,
      renderWrapper({ node, python, secrets, workspace, log, pins }),
      { mode: 0o600, flag: 'wx' },
    );
    written.push(wrapper);
    for (const [name, text] of Object.entries(units)) {
      fs.writeFileSync(join(unitDirectory, name), text, {
        mode: 0o600,
        flag: 'wx',
      });
      written.push(join(unitDirectory, name));
    }
    systemctl('daemon-reload');
    systemctl('enable', '--now', TIMER);
  } catch (error) {
    // A half-finished install must not block the next reviewed install: undo a
    // possible enable symlink first, then the written files, then reload.
    try {
      systemctl('disable', '--now', TIMER);
    } catch {
      // Nothing was enabled.
    }
    for (const path of written) fs.rmSync(path, { force: true });
    try {
      systemctl('daemon-reload');
    } catch {
      // The user manager will reload on the next login.
    }
    throw error;
  }
  return {
    installed: true,
    hourly: true,
    userTimerOnly: true,
    passwordStored: false,
    credentialsCopied: false,
    pinnedFiles: pins.length,
  };
}

function inspect() {
  const show = (unit, properties) => {
    try {
      return Object.fromEntries(
        systemctl('show', unit, '-p', properties.join(','))
          .trim()
          .split('\n')
          .map((line) => line.split(/=(.*)/s).slice(0, 2)),
      );
    } catch {
      return null;
    }
  };
  const timer = show(TIMER, [
    'LoadState',
    'ActiveState',
    'NextElapseUSecRealtime',
    'LastTriggerUSec',
  ]);
  const service = show(SERVICE, ['Result', 'ExecMainStatus', 'ActiveState']);
  let linger = null;
  try {
    linger = execFileSync(
      'loginctl',
      ['show-user', os.userInfo().username, '-p', 'Linger', '--value'],
      { encoding: 'utf8', timeout: 10000 },
    ).trim();
  } catch {
    // loginctl is optional for this read-only report.
  }
  return {
    installed: timer?.LoadState === 'loaded',
    timer,
    service,
    linger,
  };
}

function remove(workspace = scriptWorkspace()) {
  const unitDirectory = join(os.homedir(), '.config/systemd/user');
  const timer = join(unitDirectory, TIMER);
  try {
    systemctl('disable', '--now', TIMER);
  } catch (error) {
    // Only an already absent timer may be ignored; a failed stop is reported.
    if (fs.existsSync(timer)) throw error;
  }
  // The generated wrapper embeds the pins, so it is removed with the units and
  // the next reviewed source needs a fresh --install. Evidence/logs are kept.
  for (const path of [
    timer,
    join(unitDirectory, SERVICE),
    join(workspace, '.local/contabo-recovery/managed-sync-timer.mjs'),
  ]) {
    if (fs.existsSync(path)) {
      regularFile(path);
      fs.unlinkSync(path);
    }
  }
  systemctl('daemon-reload');
  return { installed: false, archivesDeleted: false };
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  try {
    if (process.platform !== 'linux' || process.argv.length !== 3)
      throw Error('Linux explicit timer action required');
    const action = {
      '--install': install,
      '--inspect': inspect,
      '--remove': remove,
      '--run': () => {
        systemctl('start', SERVICE, '--no-block');
        return { started: true };
      },
    }[process.argv[2]];
    if (!action) throw Error('Explicit timer action required');
    console.log(JSON.stringify(action()));
  } catch {
    console.error('Recovery sync timer action stopped safely.');
    process.exitCode = 1;
  }
}
